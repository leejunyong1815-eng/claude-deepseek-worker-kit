"""Offline installer; credentials stay in a private local shell environment file."""
import argparse
import getpass
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from string import Template

KIT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(KIT / "bin"))
from _kit_env import configure
configure()
BACKEND_DEFAULTS = json.loads((KIT / "config/backend.defaults.json").read_text())
ROLES = {"plan": "planner", "research": "researcher", "impl": "implementer",
         "test": "test-author", "run": "runner", "analysis": "analyst", "review": "reviewer", "qwen": "compute-runner"}


def load(path):
    values = {}
    for line in path.read_text().splitlines():
        line = line.removeprefix("export ").strip()
        if not line or line.startswith("#"):
            continue
        name, sep, value = line.partition("=")
        if sep and re.fullmatch(r"[A-Z_]+", name):
            tokens = shlex.split(value, comments=True)
            if len(tokens) > 1:
                raise ValueError("unsupported setting syntax: " + name)
            values[name] = tokens[0] if tokens else ""
    return values


def write(path, values):
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".env-")
    try:
        with os.fdopen(fd, "w") as out:
            out.write("# Private lab backend configuration. Do not commit or share.\n")
            for name, value in values.items():
                out.write(f"export {name}={shlex.quote(value)}\n")
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def configure_gateway(conf, replace=False):
    """One private connection for every worker profile; profile files retain models."""
    target = conf / "gateway.env"
    if target.is_file() and not replace:
        return
    values = load(conf / "env") if (conf / "env").is_file() else {}
    if not values:
        candidates = sorted(conf.glob("env.*"))
        values = load(candidates[0]) if candidates else dict(BACKEND_DEFAULTS)
    url = values.get("LLM_BASE_URL", BACKEND_DEFAULTS["LLM_BASE_URL"])
    # Do not forward a previous server's key when creating the new lab gateway.
    if url.rstrip("/") == "http://133.186.146.224:8081":
        values = dict(BACKEND_DEFAULTS)
    connection = {k: values.get(k, "") for k in ("LLM_BASE_URL", "LLM_AUTH_MODE", "LLM_API_KEY")}
    connection["LLM_BASE_URL"] = values.get("LLM_BASE_URL", BACKEND_DEFAULTS["LLM_BASE_URL"])
    connection["LLM_AUTH_MODE"] = values.get("LLM_AUTH_MODE", "api_key" if values.get("LLM_API_KEY") else "none")
    if target.is_file():
        backup = Path(tempfile.mkdtemp(prefix="gateway-backup.", dir=conf))
        shutil.copy2(target, backup / target.name)
    write(target, connection)
    print("Shared worker gateway configured (credentials hidden).")


def render(conf):
    for path in sorted(conf.glob("env*")):
        if path.name != "env" and not path.name.startswith("env."):
            continue
        values = load(path)
        values.setdefault("WORKER_NAME", "llm-worker")
        values.setdefault("LLM_MODEL", "unconfigured lab model")
        values["CONTEXT_LINE"] = "Use the configured context budget; keep evidence concise."
        values["ROLE_SECTION"] = ""  # selected at launch so task roles can override profiles
        text = Template((KIT / "prompts/worker.md.tmpl").read_text()).safe_substitute(values)
        (conf / ("worker" + path.name[3:] + ".md")).write_text(text)
    roles = conf / "roles"
    roles.mkdir(exist_ok=True)
    for src in (KIT / "prompts").glob("role-*.md.tmpl"):
        shutil.copyfile(src, roles / src.name.removesuffix(".tmpl"))


def setup_path(conf, prefix):
    """Opt-in Bash setup; keep existing rc content and avoid duplicate entries."""
    script = conf / "shell.sh"
    text = ("# Generated by Local Worker Kit install.sh --setup-path\n"
            f"_LLM_WORKER_BIN={shlex.quote(str(prefix))}\n"
            f"_LLM_CLAUDE_BIN={shlex.quote(str(Path.home() / '.local/bin'))}\n"
            'for _LLM_PATH_ENTRY in "$_LLM_CLAUDE_BIN" "$_LLM_WORKER_BIN"; do\n'
            '    IFS=: read -r -a _LLM_OLD_PATH <<< "${PATH:-}"\n'
            '    _LLM_NEW_PATH=("$_LLM_PATH_ENTRY")\n'
            '    for _LLM_COMPONENT in "${_LLM_OLD_PATH[@]}"; do\n'
            '        [ "$_LLM_COMPONENT" = "$_LLM_PATH_ENTRY" ] || _LLM_NEW_PATH+=("$_LLM_COMPONENT")\n'
            '    done\n'
            '    export PATH="$(IFS=:; printf \'%s\' "${_LLM_NEW_PATH[*]}")"\n'
            'done\n'
            'unset _LLM_WORKER_BIN _LLM_CLAUDE_BIN _LLM_PATH_ENTRY _LLM_OLD_PATH _LLM_NEW_PATH _LLM_COMPONENT\n'
            f"export LLM_WORKER_CONF_DIR={shlex.quote(str(conf))}\n")
    if script.exists() and script.read_text() != text:
        backup = Path(tempfile.mkdtemp(prefix="path-backup.", dir=conf))
        shutil.copy2(script, backup / script.name)
    script.write_text(text)
    script.chmod(0o600)
    rc = Path.home() / ".bashrc"
    source = f"[ ! -f {shlex.quote(str(script))} ] || . {shlex.quote(str(script))}"
    existing = rc.read_text() if rc.exists() else ""
    if source not in existing.splitlines():
        with rc.open("a") as out:
            out.write("\n# DeepSeek worker commands\n" + source + "\n")
    print(f"Bash PATH configured: {rc}")
    print(f"For this terminal: . {shlex.quote(str(script))}")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--prefix", type=Path, default=Path(os.environ.get("PREFIX", "~/.local/bin")))
    p.add_argument("--non-interactive", action="store_true")
    p.add_argument("--install-only", action="store_true", help="install tools/templates without backend credentials")
    p.add_argument("--update", action="store_true", help="preserve settings; back up and regenerate prompts offline")
    p.add_argument("--render", action="store_true")
    p.add_argument("--profile", default="")
    p.add_argument("--import-config", type=Path, action="append", default=[], help="import legacy servers/profiles into the unified private configuration")
    p.add_argument("--migrate-backend", action="store_true", help="explicitly update the selected saved profile to current lab endpoint/model/context; preserve credentials")
    p.add_argument("--check", action="store_true", help="check local tools/Claude flags without installing or calling a model")
    p.add_argument("--setup-path", action="store_true", help="write shell.sh and add one source line to ~/.bashrc")
    probe = p.add_mutually_exclusive_group()
    probe.add_argument("--probe", action="store_true", help="explicitly send small API compatibility requests")
    probe.add_argument("--skip-probe", action="store_true", help="compatibility alias; no probe is the default")
    args = p.parse_args()
    if args.check and args.migrate_backend:
        p.error("--check cannot migrate configuration")
    if args.check:
        if any((args.install_only, args.update, args.render, args.profile, args.probe, args.setup_path)):
            p.error("--check cannot be combined with installation modes")
        return subprocess.run([sys.executable, str(KIT / "bin/worker-doctor")], check=False).returncode
    if args.render and args.setup_path:
        p.error("--setup-path requires installation, not --render")
    conf = Path(os.environ.get("LLM_WORKER_CONF_DIR", "~/.config/local-worker")).expanduser().resolve()
    if args.import_config and not any(k in os.environ for k in ("DEEPSEEK_WORKER_CONF_DIR","CLAUDE_WORKER_CONF_DIR")) and conf.name in ("claude-worker","deepseek-worker"):
        conf=Path.home()/".config/local-worker"
    legacy_config=(conf/"env").is_file() and not (conf/"gateway.env").is_file()
    if "--prefix" not in sys.argv and "PREFIX" not in os.environ and conf.name=="deepseek-worker" and (Path.home()/".local/deepseek-worker/bin").is_dir():
        args.prefix=Path.home()/".local/deepseek-worker/bin"
    if args.migrate_backend and any((args.update, args.render, args.install_only)):
        p.error("--migrate-backend cannot be combined with other installation modes")
    if args.profile and not re.fullmatch(r"[A-Za-z0-9_-]+", args.profile):
        p.error("invalid profile")
    if sum((args.install_only, args.update, args.render)) > 1 or (args.update and args.profile):
        p.error("--install-only, --update and --render are exclusive; --update cannot select a profile")
    if (args.update or args.render) and not (conf / "env").is_file():
        p.error("no default configuration; install/configure the lab backend first")
    if args.probe and (args.install_only or args.update or args.render):
        p.error("--probe is only available during backend configuration")
    values = None
    target = conf / ("env" + ("." + args.profile if args.profile else ""))
    if not (args.install_only or args.update or args.render):
        inherited = load(conf / "env") if (conf / "env").is_file() else {}
        if target.is_file() and os.environ.get("FORCE_ENV") != "1" and not args.migrate_backend:
            values = load(target)
            print("Existing configuration preserved (FORCE_ENV=1 to replace explicitly).")
        else:
            fields = ("LLM_BASE_URL", "LLM_API_KEY", "LLM_MODEL", "LLM_CONTEXT_WINDOW")
            values = {k: os.environ.get(k, inherited.get(k, BACKEND_DEFAULTS.get(k, ""))) for k in fields}
            if args.migrate_backend:
                values = dict(load(target) if target.is_file() else inherited, **{k: BACKEND_DEFAULTS[k] for k in ("LLM_BASE_URL", "LLM_MODEL", "LLM_CONTEXT_WINDOW")})
            if args.profile == "qwen":
                values["LLM_MODEL"] = os.environ.get("LLM_MODEL", BACKEND_DEFAULTS["QWEN_MODEL"])
            default_mode = "api_key" if values.get("LLM_API_KEY") else BACKEND_DEFAULTS.get("LLM_AUTH_MODE", "api_key")
            mode = os.environ.get("LLM_AUTH_MODE", values.get("LLM_AUTH_MODE", inherited.get("LLM_AUTH_MODE", default_mode)))
            if mode not in {"api_key", "none"}:
                p.error("LLM_AUTH_MODE must be api_key or none")
            values["LLM_AUTH_MODE"] = mode
            if not args.non_interactive:
                for name in fields:
                    if name == "LLM_API_KEY" and mode == "none":
                        continue
                    answer = (getpass.getpass("Lab API key (hidden; Enter keeps existing): ") if name == "LLM_API_KEY"
                              else input(f"{name} [{values[name]}]: "))
                    values[name] = answer or values[name]
            for name in fields:
                if name == "LLM_API_KEY" and mode == "none":
                    continue
                value = values[name]
                if not value or "CHANGE_ME" in value or value in {"none", "dummy"}:
                    p.error(f"{name} is required; obtain the lab server settings (no official API default)")
            from urllib.parse import urlsplit
            url = urlsplit(values["LLM_BASE_URL"].rstrip("/"))
            if url.scheme not in {"http", "https"} or not url.hostname or url.username or url.password or url.query or url.fragment:
                p.error("LLM_BASE_URL must be an http(s) endpoint without credentials/query/fragment")
            if url.path.rstrip("/").endswith("/v1"):
                p.error("remove the trailing /v1; Claude Code appends /v1/messages")
            if not values["LLM_CONTEXT_WINDOW"].isdigit() or int(values["LLM_CONTEXT_WINDOW"]) <= 0:
                p.error("LLM_CONTEXT_WINDOW must be the lab server's positive context limit")
            values["LLM_BASE_URL"] = values["LLM_BASE_URL"].rstrip("/")
            values.update(LLM_DISABLE_BETAS="1", LLM_DISABLE_PROMPT_CACHING="0",
                          WORKER_NAME="llm-worker" + ("-" + args.profile if args.profile else ""),
                          WORKER_ROLE=ROLES.get(args.profile, ""), COMPUTE_HOST="")
    conf.mkdir(parents=True, exist_ok=True, mode=0o700)
    conf.chmod(0o700)
    if not args.render:
        prefix = args.prefix.expanduser().resolve()
        prefix.mkdir(parents=True, exist_ok=True)
        for src in (KIT / "bin").iterdir():
            if src.is_file():
                shutil.copyfile(src, prefix / src.name)
                (prefix / src.name).chmod(0o644 if src.name.startswith("_") and src.suffix == ".py" else 0o755)
        (conf / "kit_dir").write_text(str(KIT) + "\n")
        print(f"Installed commands: {prefix}")
        if args.setup_path:
            setup_path(conf, prefix)
        elif str(prefix) not in os.environ.get("PATH", "").split(os.pathsep):
            print(f"Add to PATH: export PATH={shlex.quote(str(prefix))}:\"$PATH\"")
    if args.install_only:
        print("Backend unconfigured. Configure later with ./install.sh; no API requests were sent.")
        return
    if args.update:
        backup = Path(tempfile.mkdtemp(prefix="prompt-backup.", dir=conf))
        for src in conf.glob("worker*.md"):
            shutil.copy2(src, backup / src.name)
        if (conf / "roles").is_dir():
            shutil.copytree(conf / "roles", backup / "roles")
        print(f"Prompt backup: {backup}")
    if values is not None and (not target.is_file() or os.environ.get("FORCE_ENV") == "1" or args.migrate_backend):
        if target.is_file():
            backup = Path(tempfile.mkdtemp(prefix="backend-backup.", dir=conf))
            shutil.copy2(target, backup / target.name)
        write(target, values)
    from _config_migration import import_profiles
    if legacy_config:
        import_profiles(conf,conf,in_place=True)
    for source in args.import_config:
        prefix=source.name.removesuffix("-worker")
        print("Imported profiles:",import_profiles(source,conf,prefix=prefix))
    configure_gateway(conf, replace=(not args.profile and values is not None and
                                    (args.migrate_backend or os.environ.get("FORCE_ENV") == "1")))
    render(conf)
    print("Prompts rendered. Code workspace: local/WSL; explicit compute jobs may use SSH. Worker effort is left to Claude/backend defaults.")
    if args.probe:
        command = [str(args.prefix.expanduser().resolve() / "llm-probe")]
        if args.profile:
            command += ["-P", args.profile]
        subprocess.run(command, check=True)


if __name__ == "__main__":
    sys.exit(main())
